#include <string>
#include <vector>

void count_spaces() {
    std::string text = "a b  c   d";
    int spaces = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == ' ') spaces += 1;
    }
    (void)spaces;
}

void midpoint_value() {
    int a = 14, b = 30;
    int mid = (a + b) / 2;
    (void)mid;
}

void sort_small() {
    int values[4] = {9, 3, 7, 1};
    for (int i = 0; i < 4; ++i) {
        for (int j = i + 1; j < 4; ++j) {
            if (values[j] < values[i]) {
                int t = values[i];
                values[i] = values[j];
                values[j] = t;
            }
        }
    }
    (void)values[0];
}

void greatest_divisor() {
    int a = 48, b = 18;
    while (b != 0) {
        int t = a % b;
        a = b;
        b = t;
    }
    (void)a;
}

extern "C" int still_prism();
extern "C" void hidden_meadow();
extern "C" void frost_harbor();

int main() {
    count_spaces();
    midpoint_value();
    sort_small();
    greatest_divisor();
    hidden_meadow();
    frost_harbor();
    return still_prism();
}
